import { test, expect } from '@playwright/test'
test('real production server registers a customer, persists a COD order, restores the session and cancels once', async ({ page, context }) => {
  await page.goto('/signup')
  await page.getByLabel('Full name', { exact: true }).fill('Production QA Customer')
  await page.getByLabel('Email', { exact: true }).fill('deployment-qa@example.test')
  await page.getByLabel('Password', { exact: true }).fill('fixture-password-12345')
  await page.getByLabel('Confirm password', { exact: true }).fill('fixture-password-12345')
  await page.getByRole('checkbox').check(); await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/shop$/)
  expect((await context.cookies()).find(cookie => cookie.name === 'aurelia.sid')).toMatchObject({ httpOnly: true, secure: true, sameSite: 'Lax' })
  await page.goto('/product/deployment-cleanser'); await page.getByRole('button', { name: 'Add to bag', exact: true }).click()
  await page.getByRole('link', { name: 'Cart', exact: true }).first().click()
  await expect(page.getByText('Deployment Cleanser', { exact: true }).first()).toBeVisible()
  await page.goto('/checkout')
  for (const [label, value] of Object.entries({ 'Full name': 'Production QA Customer', 'Mobile number': '9876543210', 'Shipping address': '10 Test Road', City: 'Delhi', State: 'Delhi', 'PIN code': '110001' })) await page.getByLabel(label, { exact: true }).fill(value)
  await page.getByRole('radio', { name: 'Cash on delivery' }).check(); await page.getByRole('button', { name: 'Place order' }).click()
  await expect(page.getByRole('heading', { name: 'Order placed — payment due on delivery.' })).toBeVisible()
  expect(new URL(page.url()).pathname).toMatch(/^\/orders\/[a-f0-9]{24}$/)
  await page.reload(); await expect(page.getByRole('heading', { name: 'Order placed — payment due on delivery.' })).toBeVisible()
  page.once('dialog', dialog => dialog.accept()); await page.getByLabel('Cancellation reason').fill('Deployment QA test')
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Order cancelled.' })).toBeVisible()
  await page.reload(); await expect(page.getByRole('heading', { name: 'Order cancelled.' })).toBeVisible()
})
